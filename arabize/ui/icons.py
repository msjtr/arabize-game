@lru_cache(maxsize=256)
def pixmap(name: str, color: str = "#E7B964", size: int = 22, stroke: float = 2.0) -> QPixmap:
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" '
           f'stroke="{color}" stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round">{PATHS[name]}</svg>')
    r = QSvgRenderer(QByteArray(svg.encode()))
    pm = QPixmap(size * 2, size * 2)
    pm.fill(Qt.transparent)
    p = QPainter(pm)
    r.render(p, QRectF(0, 0, size * 2, size * 2))
    p.end()
    pm.setDevicePixelRatio(2)
    return pm


def icon(name: str, color: str = "#C9D0EA", active: str = "#1A1204", size: int = 22) -> QIcon:
    ic = QIcon()
    ic.addPixmap(pixmap(name, color, size), QIcon.Normal, QIcon.Off)
    ic.addPixmap(pixmap(name, active, size), QIcon.Normal, QIcon.On)
    ic.addPixmap(pixmap(name, "#5D6488", size), QIcon.Disabled, QIcon.Off)
    return ic


